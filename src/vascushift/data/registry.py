"""
Dataset registry: the single source of truth for which datasets VascuShift uses,
what they contain, how they can be accessed and what their real status is.

Status vocabulary (``status`` field):
    downloaded      - open data, fetched by ``scripts/download_data.py`` into data/raw
    transcribed     - published group-level numbers transcribed into data/external
    metadata_only   - only catalogue metadata is retrievable; no data files exist
    login_required  - files exist but need a (free) account login to download
    request_required- data must be requested from the archive / authors
    synthetic       - generated in code; never to be reported as measured data

Provenance levels (``provenance`` column of the common physiology table):
    raw_individual       - per-subject values read from original data files
    published_aggregate  - group mean / CI / SD transcribed from a paper table or text
    synthetic            - generated by code
"""

